-- Migração aditiva para Oracle. Executar primeiro em homologação e com backup.
-- A tabela autorizacao_solicitada permanece inalterada durante a transição.

ALTER TABLE ocorrencias ADD tipo_negocio VARCHAR2(60) DEFAULT 'OUTRA' NOT NULL;
ALTER TABLE formularios ADD nome VARCHAR2(255);
ALTER TABLE formularios ADD dados_json CLOB;

CREATE TABLE ocorrencia_tipo_config (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_negocio VARCHAR2(60) NOT NULL,
    id_funcionalidade NUMBER,
    id_tipo_ocorrencia NUMBER,
    id_assunto NUMBER,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT ck_ocorr_tipo_cfg_ativo CHECK (ativo IN (0, 1))
);

CREATE UNIQUE INDEX uk_ocorrencia_tipo_config ON ocorrencia_tipo_config (
    tipo_negocio,
    NVL(id_funcionalidade, -1),
    NVL(id_tipo_ocorrencia, -1),
    NVL(id_assunto, -1)
);

CREATE TABLE ocorrencia_arquivo (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id NUMBER NOT NULL,
    nome_original VARCHAR2(255) NOT NULL,
    tipo_mime VARCHAR2(150),
    tamanho_bytes NUMBER,
    campo_origem VARCHAR2(255),
    hash_sha256 VARCHAR2(64),
    conteudo BLOB NOT NULL,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ocorr_arquivo_ocorr FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias(id)
);

CREATE INDEX ix_ocorr_arquivo_ocorrencia ON ocorrencia_arquivo(ocorrencia_id);
CREATE UNIQUE INDEX uk_ocorr_arquivo_hash ON ocorrencia_arquivo(ocorrencia_id, hash_sha256);

CREATE TABLE ocorrencia_tag (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id NUMBER NOT NULL,
    chave VARCHAR2(255) NOT NULL,
    valor VARCHAR2(1000),
    CONSTRAINT fk_ocorr_tag_ocorr FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias(id)
);

CREATE INDEX ix_ocorr_tag_ocorrencia ON ocorrencia_tag(ocorrencia_id);

CREATE TABLE ocorrencia_status_historico (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ocorrencia_id NUMBER NOT NULL,
    status_id VARCHAR2(100),
    descricao VARCHAR2(255) NOT NULL,
    origem VARCHAR2(30) DEFAULT 'CRM' NOT NULL,
    atribuido_em TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_ocorr_status_ocorr FOREIGN KEY (ocorrencia_id) REFERENCES ocorrencias(id)
);

CREATE INDEX ix_ocorr_status_ocorrencia ON ocorrencia_status_historico(ocorrencia_id, atribuido_em);

