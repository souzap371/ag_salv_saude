-- Migração Oracle manual: BENEFICIARIOS.ID passa a armazenar a CHAVE_UNICA textual.
-- Executar primeiro em homologação, com backup e janela de manutenção.
-- O script pressupõe as colunas BENEFICIARIOS.ID e OCORRENCIAS.BENEFICIARIO_ID
-- criadas pelo Hibernate.

-- Pré-validação: ambas as consultas devem retornar zero antes da migração.
SELECT COUNT(*) AS CHAVES_NULAS
  FROM BENEFICIARIOS
 WHERE CHAVE_UNICA IS NULL OR TRIM(CHAVE_UNICA) IS NULL;

SELECT COUNT(*) AS CHAVES_DUPLICADAS
  FROM (
        SELECT TRIM(CHAVE_UNICA)
          FROM BENEFICIARIOS
         GROUP BY TRIM(CHAVE_UNICA)
        HAVING COUNT(*) > 1
       );

ALTER TABLE BENEFICIARIOS ADD (ID_CHAVE_UNICA VARCHAR2(255));
UPDATE BENEFICIARIOS
   SET ID_CHAVE_UNICA = TRIM(CHAVE_UNICA);

ALTER TABLE OCORRENCIAS ADD (BENEFICIARIO_ID_NOVO VARCHAR2(255));
UPDATE OCORRENCIAS O
   SET O.BENEFICIARIO_ID_NOVO = (
       SELECT B.ID_CHAVE_UNICA
         FROM BENEFICIARIOS B
        WHERE B.ID = O.BENEFICIARIO_ID
   );

-- DROP PRIMARY KEY CASCADE remove também a FK antiga de OCORRENCIAS.
ALTER TABLE BENEFICIARIOS DROP PRIMARY KEY CASCADE;
ALTER TABLE OCORRENCIAS DROP COLUMN BENEFICIARIO_ID;
ALTER TABLE BENEFICIARIOS DROP COLUMN ID;

ALTER TABLE BENEFICIARIOS RENAME COLUMN ID_CHAVE_UNICA TO ID;
ALTER TABLE OCORRENCIAS RENAME COLUMN BENEFICIARIO_ID_NOVO TO BENEFICIARIO_ID;

-- ID passa a ser a única representação da chave do beneficiário.
ALTER TABLE BENEFICIARIOS DROP COLUMN CHAVE_UNICA;

ALTER TABLE BENEFICIARIOS
  ADD CONSTRAINT PK_BENEFICIARIOS PRIMARY KEY (ID);

ALTER TABLE OCORRENCIAS
  ADD CONSTRAINT FK_OCORRENCIAS_BENEFICIARIO
      FOREIGN KEY (BENEFICIARIO_ID) REFERENCES BENEFICIARIOS(ID);

COMMIT;

-- Pós-validação esperada: VARCHAR2 em ambas as colunas.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, DATA_LENGTH, NULLABLE
  FROM USER_TAB_COLUMNS
 WHERE (TABLE_NAME = 'BENEFICIARIOS' AND COLUMN_NAME = 'ID')
    OR (TABLE_NAME = 'OCORRENCIAS' AND COLUMN_NAME = 'BENEFICIARIO_ID')
 ORDER BY TABLE_NAME, COLUMN_NAME;
