CREATE TABLE mosia_status_config (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_status_mosia NUMBER NOT NULL,
    id_tipo_ocorrencia_mosia NUMBER NOT NULL,
    descricao VARCHAR2(255) NOT NULL,
    ativo NUMBER(1) DEFAULT 1 NOT NULL,
    origem VARCHAR2(30) NOT NULL,
    primeira_identificacao TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    ultima_identificacao TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT ck_mosia_status_cfg_ativo CHECK (ativo IN (0, 1)),
    CONSTRAINT uk_mosia_status_tipo UNIQUE (id_status_mosia, id_tipo_ocorrencia_mosia)
);

CREATE INDEX ix_mosia_status_tipo
    ON mosia_status_config(id_tipo_ocorrencia_mosia, id_status_mosia);

